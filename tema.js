function trocarTema() {
  const raiz = document.documentElement, claro = raiz.dataset.tema !== "claro";
  raiz.classList.add("trocando");
  claro ? (raiz.dataset.tema = "claro") : delete raiz.dataset.tema;
  localStorage.setItem("tema", claro ? "claro" : "escuro");
  document.querySelectorAll(".tema").forEach((b) => (b.innerHTML = ic(claro ? "lua" : "sol")));
  setTimeout(() => raiz.classList.remove("trocando"), 600);
}
